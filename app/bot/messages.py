def language_name(code: str) -> str:
    return LANG_NAMES.get((code or "").lower(), code or "نامشخص")


def fmt_seconds(seconds: float) -> str:
    """Human readable duration in Persian, e.g. «۱ ساعت و ۲۳ دقیقه»."""
    seconds = int(round(max(0, seconds)))
    hours, rem = divmod(seconds, 3600)
    minutes, secs = divmod(rem, 60)
    parts = []
    if hours:
        parts.append("%d ساعت" % hours)
    if minutes:
        parts.append("%d دقیقه" % minutes)
    if secs or not parts:
        parts.append("%d ثانیه" % secs)
    return " و ".join(parts)


def progress_bar(fraction: float, width: int = 10) -> str:
    fraction = min(1.0, max(0.0, fraction))
    filled = int(round(fraction * width))
    return "▰" * filled + "▱" * (width - filled) + " %d٪" % int(fraction * 100)
